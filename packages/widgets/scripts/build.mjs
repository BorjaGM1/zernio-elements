/**
 * Builds each widget to one self-contained HTML file (vite-plugin-singlefile can only inline a single
 * entry per build, so we run one build per widget), then emits dist/index.js + dist/index.d.ts that
 * export the HTML as strings for the MCP server's ui:// resources.
 *
 *   node scripts/build.mjs            widgets + index
 *   node scripts/build.mjs --harness  also the dev harness (dist-harness/), used by dev + screenshots
 */
import { readFile, writeFile, mkdir, rm } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import { build } from "vite";
import react from "@vitejs/plugin-react";
import tailwindcss from "@tailwindcss/vite";
import { viteSingleFile } from "vite-plugin-singlefile";

const pkg = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const WIDGETS = [
  { file: "preview-post", exportName: "previewPostHtml" },
  { file: "analytics", exportName: "analyticsHtml" },
  { file: "accounts", exportName: "accountsHtml" },
  { file: "render-view", exportName: "renderViewHtml" },
];

async function buildOne(root, entry, outDir) {
  await build({
    configFile: false,
    root,
    logLevel: "warn",
    plugins: [react(), tailwindcss(), viteSingleFile({ removeViteModuleLoader: true })],
    // Preact's React compatibility layer instead of react-dom: about a third of each single-file widget.
    // ZE_WIDGETS_REACT=1 builds with real React (to compare if a widget ever misbehaves).
    resolve:
      process.env.ZE_WIDGETS_REACT === "1"
        ? {}
        : {
            alias: [
              { find: /^react-dom\/client$/, replacement: "preact/compat/client" },
              { find: /^react-dom$/, replacement: "preact/compat" },
              { find: /^react\/jsx-runtime$/, replacement: "preact/jsx-runtime" },
              { find: /^react\/jsx-dev-runtime$/, replacement: "preact/jsx-dev-runtime" },
              { find: /^react$/, replacement: "preact/compat" },
            ],
            dedupe: ["preact"],
          },
    build: {
      outDir,
      emptyOutDir: false,
      assetsInlineLimit: Number.MAX_SAFE_INTEGER,
      cssCodeSplit: false,
      modulePreload: { polyfill: false },
      reportCompressedSize: false,
      rollupOptions: { input: resolve(root, `${entry}.html`) },
    },
  });
}

// --harness-only rebuilds just the test host and leaves dist/ alone: other packages (apps/mcp) import
// dist/index.js, and deleting it mid-run made their tests flaky under turbo.
const harnessOnly = process.argv.includes("--harness-only");
const harness = harnessOnly || process.argv.includes("--harness");
const dist = resolve(pkg, "dist");
if (!harnessOnly) {
await rm(dist, { recursive: true, force: true });
await mkdir(dist, { recursive: true });

for (const w of WIDGETS) await buildOne(resolve(pkg, "src/entries"), w.file, dist);

const lines = ["// Generated by scripts/build.mjs. Each string is a complete, self-contained HTML document."];
const types = ["// Generated by scripts/build.mjs."];
const sizes = [];
for (const w of WIDGETS) {
  const html = await readFile(resolve(dist, `${w.file}.html`), "utf8");
  lines.push(`export const ${w.exportName} = ${JSON.stringify(html)};`);
  types.push(`/** dist/${w.file}.html as a string (mime type text/html;profile=mcp-app). */`, `export declare const ${w.exportName}: string;`);
  sizes.push(`${w.file}.html ${(Buffer.byteLength(html) / 1024).toFixed(1)} kB`);
}
await writeFile(resolve(dist, "index.js"), lines.join("\n") + "\n");
await writeFile(resolve(dist, "index.d.ts"), types.join("\n") + "\n");
console.log(`widgets: ${sizes.join(", ")}`);
}

if (harness) {
  const out = resolve(pkg, "dist-harness");
  await rm(out, { recursive: true, force: true });
  await buildOne(resolve(pkg, "src/harness"), "host", out);
  console.log("harness: dist-harness/host.html");
}
